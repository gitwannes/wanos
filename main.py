@app.post("/api/event")
async def inject_event(request: GenericEventRequest, req: Request) -> dict[str, Union[str, Event]]:
    e_type_str = request.type.value if hasattr(request.type, 'value') else str(request.type)
    # Normalize catalog keys → UUID before admin checks / dispatch.
    bus_token = to_bus_token(e_type_str)

    # Block users/kiosks from performing system-level administration toggles
    admin_only_events = ["CONFIG_RELOAD_REQUESTED", "SYSTEM_SWEEP_REQUESTED", "SIMULATIONS_TOGGLED"]
    if req.state.role != "admin":
        if e_type_str in admin_only_events or e_type_str.endswith("_TOGGLED"):
            return JSONResponse(status_code=403, content={"error": "Forbidden: Admin privileges required."})

    try:
        e_type: Any = EventType(bus_token)
    except ValueError:
        e_type = bus_token

    event: Event = Event(type=e_type, payload=request.payload)
    state_manager.dispatch(event)
    return {"status": "Event dispatched", "event": event}


@app.get("/api/state/sse")
async def sse_state_stream(request: Request):
    """
    Delta SSE stream. Emits domain subtrees when state changes (B10H event-driven hub).
    Payload format: {"domain": "<key>", "data": { ... }}
    The frontend fetches /api/state on connect for the full snapshot, then
    applies these partial updates by domain key as they arrive.

    First byte is an immediate ping: behind nginx, awaiting is_disconnected()
    before any yield returned 200 + empty body (~10 ms) and EventSource.onerror.
    X-Accel-Buffering tells nginx 1.18 not to buffer the stream.
    """
    import time

    def _ping_line() -> str:
        return f"data: {json.dumps({'domain': 'ping', 'data': {}})}\n\n"

    async def event_generator() -> AsyncGenerator[str, None]:
        client = await sse_hub.subscribe()
        last_ping_time = time.time()
        try:
            yield _ping_line()
            while not shutdown_event.is_set():
                try:
                    line = await asyncio.wait_for(client.queue.get(), timeout=5.0)
                    yield line
                    last_ping_time = time.time()
                except asyncio.TimeoutError:
                    now = time.time()
                    if now - last_ping_time >= 5.0:
                        yield _ping_line()
                        last_ping_time = now
                if await request.is_disconnected():
                    break
        except asyncio.CancelledError:
            pass
        finally:
            await sse_hub.unsubscribe(client)

    # Do not send Connection: keep-alive. HTTP/2 forbids hop-by-hop headers;
    # nginx 1.18 + listen http2 then yields Chrome net::ERR_HTTP2_PROTOCOL_ERROR
    # (200) and EventSource.onerror. Keep-alive is implicit for HTTP/1.1 proxy.
    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
        },
    )


