def _bind_sr_name_to_se_catalog(
    rule: dict[str, Any],
    *,
    events_by_id: Optional[dict[str, dict[str, Any]]] = None,
) -> None:
    """
    SR invariant: rule name always equals companion SE catalog name.

    On automations POST/PUT, if the primary wake event is a system event, overwrite
    ``name`` from the live catalog (YAML events:) or seed constant so YAML cannot
    drift (e.g. old free-text SR titles).

    B10H: pass ``events_by_id`` on list hot paths to avoid N+1 YAML reloads.
    """
    eid = _primary_trigger_event_id(rule)
    if not eid or eid not in SYSTEM_UUID_TO_KEY:
        return
    if events_by_id is not None:
        cat = events_by_id.get(eid)
    else:
        cat = find_event(eid)
    cat_name = ""
    if isinstance(cat, dict) and cat.get("name"):
        cat_name = str(cat["name"]).strip()
    if not cat_name:
        cat_name = str(SYSTEM_UUID_TO_NAME.get(eid) or "").strip()
    if cat_name:
        rule["name"] = cat_name


def _persist_automation_payload(rule: dict[str, Any]) -> dict[str, Any]:
    """
    B19: persist Domoticz branch shape only. Legacy trigger+cases / Y1 / flat → 400.
    """
    import uuid

    from core.automations_schema_b19 import (
        is_branch_rule,
        is_legacy_cases_rule,
        normalize_branch_rule,
        ordered_branch_dict,
        validate_branch_entity_ids,
        validate_branch_rule_for_enable,
    )

    if is_legacy_cases_rule(rule) or (
        isinstance(rule, dict)
        and ("trigger" in rule or "cases" in rule)
        and not is_branch_rule(rule)
    ):
        raise ValueError(
            "Legacy trigger+cases authoring is retired (B19). "
            "Use branches (If/Do). Multi-device OR leftovers wait Ship B4/H4."
        )
    if ("on" in rule) or ("off" in rule) or (
        not is_branch_rule(rule) and ("conditions" in rule or "actions" in rule)
        and "branches" not in rule
    ):
        raise ValueError(
            "Legacy Y1/flat automation payloads are retired (B19). Use branches."
        )

    if not is_branch_rule(rule):
        raise ValueError("Automation must use branches: [{ when, conditions, actions }, …].")

    br = ordered_branch_dict(normalize_branch_rule(rule))
    if not br.get("id"):
        br["id"] = str(uuid.uuid4())
    if "enabled" not in br:
        br["enabled"] = True
    _bind_sr_name_to_se_catalog(br)
    validate_branch_entity_ids(br)
    enable_err = validate_branch_rule_for_enable(br)
    if br.get("enabled", True) is not False and enable_err:
        raise ValueError(enable_err)
    if enable_err and br.get("enabled", True) is False:
        # Disabled invalid drafts are allowed (locked B19).
        pass
    return br


def _assert_one_system_listener(rule: dict[str, Any]) -> Optional[str]:
    """
    B10E: at most one SR may listen to a given system event (SE).
    Returns an error message or None.
    """
    eid = _primary_trigger_event_id(rule)
    if not eid or eid not in SYSTEM_UUID_TO_KEY:
        return None
    exclude = str(rule.get("id") or "") or None
    if count_system_event_listeners(eid, exclude_rule_id=exclude) >= 1:
        return (
            f"System event already has a listening rule (SR) "
            f"(one flow per system event). Event id={eid}."
        )
    return None


def _assert_u_rule_disable_allowed(rule: dict[str, Any]) -> Optional[str]:
    """
    B10E: cannot disable a user-event rule (UR) while its trigger UE is fire-referenced.
    Returns an error message or None. SR disable is always allowed here.
    """
    if rule.get("enabled", True) is not False:
        return None
    eid = _primary_trigger_event_id(rule)
    if not eid or eid in SYSTEM_UUID_TO_KEY:
        return None
    fire_refs = rule_fire_refs_to_event(eid)
    if not fire_refs:
        return None
    return (
        "Cannot disable: trigger event is fired as action by: "
        + ", ".join(fire_refs)
    )


def _automation_name_clash(name: str, exclude_id: Optional[str] = None) -> Optional[str]:
    """
    B10D: return conflicting rule id if name collides (trim + casefold), else None.
    Same-id update may keep its own name (exclude_id).
    """
    needle = normalize_event_name_key(name)  # trim + casefold helper
    if not needle:
        return "empty"
    for row in read_automations():
        if not isinstance(row, dict):
            continue
        rid = str(row.get("id") or "")
        if exclude_id and rid == exclude_id:
            continue
        if normalize_event_name_key(str(row.get("name") or "")) == needle:
            return rid or "?"
    return None


